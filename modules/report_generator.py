"""
Report Generator Module.
Produces standardized CSV and formatted traffic surveillance summaries.
"""
import csv
import io
import json
from typing import Dict, List, Any, Optional


class ReportGenerator:
    """
    Generates official audit-ready CSV logs and formatted surveillance bulletins.
    """

    @staticmethod
    def generate_csv_report(analyses: List[Dict[str, Any]]) -> str:
        """
        Builds a RFC-4180 compliant CSV string containing surveillance analysis summaries.
        """
        output = io.StringIO()
        fieldnames = [
            "Analysis ID",
            "File Name",
            "File Type",
            "Timestamp",
            "Total Vehicles",
            "Cars",
            "Motorcycles",
            "Buses",
            "Trucks",
            "Bicycles",
            "Trains",
            "Processing Time (s)",
            "Status",
            "Description",
            "Counting Method",
        ]
        writer = csv.DictWriter(output, fieldnames=fieldnames)
        writer.writeheader()

        for a in analyses:
            meta = {}
            if "metadata_json" in a and a["metadata_json"]:
                try:
                    meta = json.loads(a["metadata_json"])
                except Exception:
                    pass

            cats = a.get("category_counts", {})
            writer.writerow({
                "Analysis ID": a.get("id", ""),
                "File Name": a.get("file_name", ""),
                "File Type": a.get("file_type", "").upper(),
                "Timestamp": a.get("timestamp", ""),
                "Total Vehicles": a.get("total_vehicle_count", 0),
                "Cars": cats.get("car", 0),
                "Motorcycles": cats.get("motorcycle", 0),
                "Buses": cats.get("bus", 0),
                "Trucks": cats.get("truck", 0),
                "Bicycles": cats.get("bicycle", 0),
                "Trains": cats.get("train", 0),
                "Processing Time (s)": round(float(a.get("processing_time", 0.0)), 2),
                "Status": a.get("status", ""),
                "Description": a.get("description", ""),
                "Counting Method": meta.get("counting_method", "YOLOv8 Object Detection"),
            })

        return output.getvalue()

    @staticmethod
    def generate_bulletin_text(analysis: Dict[str, Any]) -> str:
        """
        Creates an official government-style incident bulletin text report.
        """
        header = "=" * 70
        title = "OFFICIAL TRAFFIC SURVEILLANCE & VEHICLE AUDIT REPORT"
        sub = "Department of Traffic Monitoring | Intelligent Transportation Analytics"
        
        cats = analysis.get("category_counts", {})
        cat_lines = []
        for k, v in cats.items():
            cat_lines.append(f"  * {k.upper():<15}: {v} units")
        cat_str = "\n".join(cat_lines) if cat_lines else "  * None recorded"

        report = f"""{header}
{title.center(70)}
{sub.center(70)}
{header}

REPORT METADATA:
  - Document ID      : TRAFFIC-AUDIT-{analysis.get('id', 'N/A')}
  - Timestamp (UTC)  : {analysis.get('timestamp', 'N/A')}
  - Source Media     : {analysis.get('file_name', 'Unknown')}
  - Media Format     : {analysis.get('file_type', 'N/A').upper()}
  - Processing Latency: {analysis.get('processing_time', 0.0):.2f} seconds
  - Surveillance Status: {analysis.get('status', 'COMPLETED')}

VEHICLE CENSUS SUMMARY:
  - TOTAL VEHICLES DETECTED: {analysis.get('total_vehicle_count', 0)}
{cat_str}

INCIDENT / SCENE CONTEXT:
  {analysis.get('description', 'No specific incident noted.')}

SURVEILLANCE ACCREDITATION:
  Generated by AI-Based Traffic Surveillance Prototype.
  Model: Ultralytics YOLOv8n (COCO-trained weights) + ByteTrack IoU Tracker.
  Notice: This report is an intelligent computer vision diagnostic summary.
{header}
"""
        return report
